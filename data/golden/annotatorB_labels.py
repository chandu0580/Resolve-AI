INTENTS = {"battery_power", "performance_crash", "keyboard_text_bug", "connectivity", "data_loss_sync",
           "apps_services", "account_store_repair", "hardware_damage", "general_complaint", "non_english", "other"}
REASONS = {"safety", "legal_media", "private_info", "hardware", "repeat_contact", "vague_hostile", "none"}


def main():
    df = pd.read_csv(CSV, dtype=str, keep_default_na=False)
    assert len(df) == 197, len(df)
    assert set(df["gid"]) == set(B), set(df["gid"]) ^ set(B)
    for gid, (intent, esc, reason, note) in B.items():
        assert intent in INTENTS, (gid, intent)
        assert reason in REASONS, (gid, reason)
        assert isinstance(esc, bool), gid
        assert (reason == "none") == (not esc), (gid, esc, reason)
        if intent in ("non_english", "other"):
            assert not esc, gid
    df["intent"] = df["gid"].map(lambda g: B[g][0])
    df["should_escalate"] = df["gid"].map(lambda g: str(B[g][1]))
    df["escalation_reason"] = df["gid"].map(lambda g: B[g][2])
    df["note"] = df["gid"].map(lambda g: B[g][3])
    df.to_csv(CSV, index=False)
    print("rows labelled:", len(df))
    print(df["intent"].value_counts().to_string())
    print("escalate True:", (df["should_escalate"] == "True").sum())
    print(df.loc[df["should_escalate"] == "True", "escalation_reason"].value_counts().to_string())


if __name__ == "__main__":
    main()
